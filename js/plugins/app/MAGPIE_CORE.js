MAGPIE.printVersion = function (version) {
  const ePrefix = "[CORE].printVersion: ";
  try {
    if (!Array.isArray(version) || version.some((n) => isNaN(n)))
      throw new Error(`'${version}' is invalid version`);
    const [major, minor, patch] = version;
    return `v${major}.${minor}.${patch}`;
  } catch (e) {
    console.error(ePrefix + e.message, e);
  }
};
